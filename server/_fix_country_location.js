function calibrate(loc, city) {
  const cands = [String(city || '').trim(), String(loc || '').trim()].filter(Boolean);
  for (const c of cands) {
    if (!c || c === '中国') continue; /* 排除中国：主体非事发地 */
    if (CITY2COUNTRY[c]) return CITY2COUNTRY[c];
    if (COUNTRY_SET.has(c)) return c;
    /* location 可能是"城市+国"或带后缀，尝试子串匹配已知城市（长名优先） */
    const keys = Object.keys(CITY2COUNTRY).sort((a, b) => b.length - a.length);
    for (const k of keys) { if (c.indexOf(k) >= 0) return CITY2COUNTRY[k]; }
  }
  return '';
}
